#!/usr/bin/env python3
"""Generate the Lumengram embedded themes in Telegram/Resources.

The dark themes are derived from the built-in "Tinted" night palette
(Telegram/Resources/night.tdesktop-theme) and the light one from the base
palette with the "Day" overrides, so contrast relationships stay as
designed in the original palettes:

- lumen-light.tdesktop-theme: the base palette with the "Day" overrides,
  blue tones shifted to lavender the same way as in Lumen Dark.
- lumen-dark.tdesktop-theme: every cold blue tone is shifted to a soft
  lavender and slightly desaturated.
- lumen-black.tdesktop-theme: Lumen Dark with the dark surfaces pulled
  down to pure black (for OLED screens); bubbles and hover states stay
  slightly lighter so they remain visible.

Semantic colors (red, green, peer name / userpic colors, file colors) stay
untouched in both.

Usage:
    python tools/lumen/make_lumen_themes.py           # write the theme files
    python tools/lumen/make_lumen_themes.py --print   # also print scheme colors
"""

import colorsys
import os
import re
import struct
import sys
import zipfile
import zlib

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
RESOURCES = os.path.join(ROOT, "Telegram", "Resources")
SOURCE = os.path.join(RESOURCES, "night.tdesktop-theme")
DAY_SOURCE = os.path.join(RESOURCES, "day-blue.tdesktop-theme")
BASE_PALETTE = os.path.join(ROOT, "Telegram", "lib_ui", "ui", "colors.palette")
TARGET_LIGHT = os.path.join(RESOURCES, "lumen-light.tdesktop-theme")
TARGET_DARK = os.path.join(RESOURCES, "lumen-dark.tdesktop-theme")
TARGET_BLACK = os.path.join(RESOURCES, "lumen-black.tdesktop-theme")

# Blue hues of the night palette (in degrees) that are moved to lavender.
HUE_FROM, HUE_TO = 175.0, 235.0
HUE_SHIFT = 42.0
SATURATION_SCALE = 0.72

# Lumen Black: surfaces at or below the window background lightness become
# pure black, lightness up to BLACK_RANGE_TOP is compressed towards black
# with a gamma curve, brighter colors are kept as is.
WINDOW_BG = "17212b"  # windowBg of the night palette.
BLACK_RANGE_TOP = 0.30
BLACK_GAMMA = 0.6
BLACK_SATURATION_SCALE = 0.5

# Same keys as kColorizeIgnoredKeys in window_themes_embedded.cpp.
IGNORED_RE = re.compile(
    r"^(historyPeer[1-8](NameFg|NameFgSelected|UserpicBg|UserpicBg2)"
    r"|msgFile[1-4](Bg|BgDark|BgOver|BgSelected)"
    r"|mediaviewFile(Red|Yellow|Green|Blue)CornerFg"
    r"|settingsIconBg([1-68]|Archive)"
    r"|premiumButtonBg[1-3]|premiumIconBg[12]"
    r"|boxTextFgGood|boxTextFgError|callIconFg)$")

COLOR_RE = re.compile(r"#([0-9a-fA-F]{6})([0-9a-fA-F]{2})?\b")
LINE_RE = re.compile(r"^\s*([A-Za-z0-9_]+)\s*:")

FIXED_DATE = (2026, 10, 20, 0, 0, 0)


def to_hls(hex6):
    r, g, b = (int(hex6[i:i + 2], 16) / 255.0 for i in (0, 2, 4))
    return colorsys.rgb_to_hls(r, g, b)


def from_hls(h, l, s):
    r, g, b = colorsys.hls_to_rgb(h, l, s)
    return "".join("%02x" % round(c * 255) for c in (r, g, b))


def shift(hex6):
    h, l, s = to_hls(hex6)
    degrees = h * 360.0
    if s < 0.04 or not (HUE_FROM <= degrees <= HUE_TO):
        return hex6.lower()
    h = ((degrees + HUE_SHIFT) % 360.0) / 360.0
    s *= SATURATION_SCALE
    return from_hls(h, l, s)


def blacken(hex6):
    h, l, s = to_hls(hex6)
    bottom = to_hls(WINDOW_BG)[1]
    if l >= BLACK_RANGE_TOP:
        return hex6.lower()
    if l <= bottom:
        return "000000"
    part = (l - bottom) / (BLACK_RANGE_TOP - bottom)
    l = BLACK_RANGE_TOP * (part ** BLACK_GAMMA)
    return from_hls(h, l, s * BLACK_SATURATION_SCALE)


def lumen_dark(hex6):
    return shift(hex6)


def lumen_black(hex6):
    return blacken(shift(hex6))


def ignored(key):
    return IGNORED_RE.match(key) is not None


def convert_palette(text, transform, title):
    result = []
    for line in text.splitlines():
        match = LINE_RE.match(line)
        if match and not ignored(match.group(1)):
            line = COLOR_RE.sub(
                lambda m: "#" + transform(m.group(1)) + (m.group(2) or "").lower(),
                line,
                count=1)
        result.append(line)
    header = (
        "// " + title + ": generated by tools/lumen/make_lumen_themes.py.\n"
        "// Edit the script, not this file.\n")
    return header + "\n".join(result) + "\n"


def png_1x1(hex6):
    def chunk(kind, data):
        body = kind + data
        return (struct.pack(">I", len(data)) + body
                + struct.pack(">I", zlib.crc32(body) & 0xffffffff))
    pixel = bytes.fromhex(hex6) + b"\xff"
    return (b"\x89PNG\r\n\x1a\n"
            + chunk(b"IHDR", struct.pack(">IIBBBBB", 1, 1, 8, 6, 0, 0, 0))
            + chunk(b"IDAT", zlib.compress(b"\x00" + pixel, 9))
            + chunk(b"IEND", b""))


def png_pixel(data):
    start = data.find(b"IDAT")
    size = struct.unpack(">I", data[start - 4:start])[0]
    raw = zlib.decompress(data[start + 4:start + 4 + size])
    return raw[1:4].hex()


def write_zip(path, files):
    with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED) as out:
        for name, data in files:
            info = zipfile.ZipInfo(name, FIXED_DATE)
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            out.writestr(info, data)


def write_theme(path, title, transform, colors, background):
    write_zip(path, [
        ("colors.tdesktop-theme",
            convert_palette(colors, transform, title).encode("utf-8")),
        ("background.png", png_1x1(transform(png_pixel(background)))),
    ])
    print("written", os.path.relpath(path, ROOT))


def day_palette():
    """Base palette text with the Day theme overrides applied in place."""
    with zipfile.ZipFile(DAY_SOURCE) as source:
        overrides = dict(
            (m.group(1), m.group(2).strip())
            for m in re.finditer(
                r"^\s*([A-Za-z0-9_]+)\s*:\s*([^;]+);",
                source.read("colors.tdesktop-theme").decode("utf-8"),
                re.M))
        background = source.read("background.png")
    line_re = re.compile(r"^(\s*)([A-Za-z0-9_]+)(\s*:\s*)([^;]+);(.*)$")
    lines = []
    with open(BASE_PALETTE, encoding="utf-8") as base:
        for line in base.read().splitlines():
            match = line_re.match(line)
            if match and match.group(2) in overrides:
                line = (match.group(1) + match.group(2) + match.group(3)
                        + overrides[match.group(2)] + ";" + match.group(5))
            lines.append(line)
    return "\n".join(lines), background


def main():
    with zipfile.ZipFile(SOURCE) as source:
        colors = source.read("colors.tdesktop-theme").decode("utf-8")
        background = source.read("background.png")

    day_colors, day_background = day_palette()
    write_theme(TARGET_LIGHT, "Lumen Light", shift, day_colors, day_background)

    write_theme(TARGET_DARK, "Lumen Dark", lumen_dark, colors, background)
    write_theme(TARGET_BLACK, "Lumen Black", lumen_black, colors, background)

    if "--print" in sys.argv:
        print("%-22s %-8s %s" % ("day key", "day", "light"))
        for name, value in [
                ("background", "7ec4ea"),
                ("sent", "d7f0ff"),
                ("received", "ffffff"),
                ("radiobuttonInactive", "d7f0ff"),
                ("radiobuttonActive", "ffffff"),
                ("accentColor", "40a7e3")]:
            print("%-22s %-8s %s" % (name, value, shift(value)))
        # Values for EmbeddedScheme / ColorizerFrom, taken from the Night
        # entries in window_themes_embedded.cpp.
        print("%-22s %-8s %-8s %s" % ("night key", "night", "dark", "black"))
        for name, value in [
                ("background", "485761"),
                ("sent", "5ca7d4"),
                ("received", "6b808d"),
                ("radiobuttonInactive", "6b808d"),
                ("radiobuttonActive", "5ca7d4"),
                ("accentColor", "5288c1"),
                ("windowBg", "17212b"),
                ("activeButtonBg", "2f6ea5"),
                ("msgInBg", "182533"),
                ("msgOutBg", "2b5278"),
                ("selectedBg", "2e70a5"),
                ("msgFileInBg", "3f96d0"),
                ("msgFileInBgSelected", "6ab4f4"),
                ("msgFileOutBg", "4c9ce2"),
                ("msgFileOutBgSelected", "58abf3")]:
            print("%-22s %-8s %-8s %s" % (
                name, value, lumen_dark(value), lumen_black(value)))


if __name__ == "__main__":
    main()
