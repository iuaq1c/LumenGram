// Generates LumenLang.java from the web client's src/lumen/lang.ts, so both apps share the same texts.
const fs = require('fs');
const [, , langTs, outJava] = process.argv;
const src = fs.readFileSync(langTs, 'utf8');
const grab = (re) => {
  const start = src.search(re);
  const open = src.indexOf('{', start);
  let depth = 0;
  for (let i = open; i < src.length; i++) {
    if (src[i] === '{') depth++;
    if (src[i] === '}' && --depth === 0) return new Function(`return (${src.slice(open, i + 1)});`)();
  }
  throw new Error('object not found');
};
const en = grab(/const EN = /);
const ru = grab(/const RU: /);
// Android wording for texts that talk about a mouse, browser tabs or Telegram Web A.
const fix = {
  en: {
    SettingsAbout: 'Unofficial Telegram client based on Telegram for Android',
    BookmarksEmpty: 'No bookmarks yet. Long-press a message and choose Add bookmark.',
    MusicSpotifyPending: 'Finish connecting Spotify in the browser, then come back.',
    BlurMedia: 'Blur media until you tap it',
    BlurMediaAbout: 'Photos, videos and stickers in chats stay blurred until you tap them.',
    IntroAbout: 'Welcome to LumenGram,\nan unofficial Telegram client.',
    IntroStart: 'Start Messaging',
  },
  ru: {
    SettingsAbout: 'Неофициальный клиент Telegram на основе Telegram для Android',
    BookmarksEmpty: 'Закладок пока нет. Удерживайте сообщение и выберите «Добавить в закладки».',
    MusicSpotifyPending: 'Завершите подключение Spotify в браузере и вернитесь в приложение.',
    BlurMedia: 'Размывать медиа, пока не нажмёте',
    BlurMediaAbout: 'Фото, видео и стикеры в чатах размыты, пока вы на них не нажмёте.',
    IntroAbout: 'Добро пожаловать в LumenGram —\nнеофициальный клиент Telegram.',
    IntroStart: 'Начать общение',
  },
};
Object.assign(en, fix.en);
Object.assign(ru, fix.ru);
const q = (s) => JSON.stringify(String(s).split(String.fromCharCode(92) + 'n').join(String.fromCharCode(10)));
const put = (name, obj) => Object.keys(obj).sort()
  .map((k) => `        ${name}.put(${q(k)}, ${q(obj[k])});`).join('\n');
const java = `/*
 * This file is part of LumenGram, a modification of Telegram for Android.
 * Generated by tools/lumen/gen_lang.js from the web client's lang.ts, do not edit by hand.
 */
package org.telegram.lumen;

import java.util.HashMap;

final class LumenLangData {
    static final HashMap<String, String> EN = new HashMap<>();
    static final HashMap<String, String> RU = new HashMap<>();

    static {
${put('EN', en)}
${put('RU', ru)}
    }

    private LumenLangData() {
    }
}
`;
fs.writeFileSync(outJava, java);
console.log(`keys: en=${Object.keys(en).length} ru=${Object.keys(ru).length}`);
